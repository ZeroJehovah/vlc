#!/usr/bin/env python3
"""Refresh JNI static plugins without mixing make-install and renamed archives.

The module list generated by compile-libvlc.sh remains the allowlist (including
its blacklist decisions). Rebuild with that script when enabling new modules.
Symbol renaming mirrors its static-module preparation step.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile


def main():
    build = Path(sys.argv[1]).resolve()
    declaration = build / 'ndk/libvlcjni-modules.c'
    names = re.findall(r'^int vlc_entry__(\w+)\s*\(', declaration.read_text(), re.M)
    if not names or len(names) != len(set(names)):
        raise RuntimeError('Missing or duplicate static module declarations')

    archives = {}
    for path in (build / 'modules').rglob('lib*_plugin.a'):
        archives.setdefault(path.name, []).append(path)
    output = build / 'ndk/static-plugins'
    output.mkdir(exist_ok=True)
    nm = os.environ.get('VLC_PLUGIN_NM', 'llvm-nm-18')
    objcopy = os.environ.get('VLC_PLUGIN_OBJCOPY', 'llvm-objcopy-18')
    public = ('AccessOpen', 'AccessClose', 'StreamOpen', 'StreamClose',
              'OpenDemux', 'CloseDemux', 'DemuxOpen', 'DemuxClose',
              'OpenFilter', 'CloseFilter', 'Open', 'Close')
    modules = []
    manifest = {}
    with tempfile.TemporaryDirectory(prefix='vlc-static-plugins-') as tmp:
        symbols_file = Path(tmp) / 'symbols'
        for name in names:
            candidates = archives.get(f'lib{name}_plugin.a', [])
            if len(candidates) != 1:
                raise RuntimeError(f'{name}: expected one built archive, got {candidates}')
            source = candidates[0]
            target = output / source.name
            symbols = subprocess.check_output(
                [nm, '-g', '--defined-only', str(source)], text=True)
            defined = {line.split()[-1] for line in symbols.splitlines()
                       if len(line.split()) >= 3}
            mapping = [f'{symbol} {symbol}__{name}' for symbol in public]
            for prefix in ('vlc_entry__', 'vlc_entry_copyright__', 'vlc_entry_license__'):
                matches = sorted(s for s in defined if s.startswith(prefix))
                if len(matches) != 1:
                    raise RuntimeError(f'{name}: expected one {prefix} symbol, got {matches}')
                mapping.append(f'{matches[0]} {prefix}{name}')
            symbols_file.write_text('\n'.join(mapping) + '\n')
            subprocess.run([objcopy, '--redefine-syms', str(symbols_file),
                            str(source), str(target)], check=True)
            modules.append(str(target))
            manifest[name] = {
                'source': str(source.relative_to(build)),
                'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                'linked_sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
            }
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Refreshed {len(modules)} static plugins from the build tree', file=sys.stderr)
    print(' '.join(modules))


if __name__ == '__main__':
    main()
